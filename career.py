def pair_info(a, b):
    key = tuple(sorted((a, b), key=lambda x: (x == 0, x)))   # ๐ อยู่ท้ายเสมอ
    label = PAIR.get(key)
    good = not (a in BAAP or b in BAAP)
    if isinstance(label, tuple): label = label[0] if good else label[1]
    return f"{a}{b} {label}", good

